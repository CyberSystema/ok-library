// This pack uses standard Greek library vocabulary rather than translated
// English. The decisions taken, so they can be checked as a set rather than one
// sentence at a time:
//
//   record .................. βιβλιογραφική εγγραφή / εγγραφή
//   copy, item .............. αντίτυπο
//   holdings ................ τι κατέχουμε (running text) / αποθέματα (formal)
//   monograph ............... μονογραφία
//   serial, periodical ...... περιοδική έκδοση, περιοδικό
//   authority, heading ...... καθιερωμένη απόδοση
//   variant form ............ παραλλαγή
//   subject heading ......... θεματική επικεφαλίδα
//   classification .......... ταξινόμηση
//   shelf mark .............. ταξιθετικός δείκτης
//   call number ............. ταξιθετικός αριθμός
//   cataloguing ............. καταλογογράφηση
//   transliteration ......... μεταγραμματισμός   (ISO 843's own term)
//   title page .............. σελίδα τίτλου
//   imprint ................. εκδοτικά στοιχεία
//   extent .................. έκταση
//   withdrawal .............. απόσυρση
//   reader, borrower ........ αναγνώστης
//   hold, reservation ....... κράτηση
//   duplicate ............... διπλότυπο
//   merge ................... συγχώνευση
//   harvesting (OAI-PMH) .... συγκομιδή
//   backup .................. αντίγραφο ασφαλείας
//
// ⚑ FOR REVIEW — the five choices least certain, listed here rather than left to
//   be discovered. Each is used consistently throughout, so changing one is a
//   single find-and-replace:
//
//   1. «ταξιθετικός δείκτης» for the local shelf mark against «ταξιθετικός
//      αριθμός» for the exported call number. Both terms are in use in Greek
//      libraries and some catalogues treat them as synonyms; this pack needs two
//      distinct words because the system holds two distinct fields.
//   2. «καθιερωμένη απόδοση» for an authority record. «Καθιερωμένος όρος» is
//      also current, and reads better for subjects than for people.
//   3. «τι κατέχουμε» as the everyday phrase for holdings. Deliberately plain;
//      «αποθέματα» is the formal term and may be preferred on screen.
//   4. «μεταγραμματισμός» for transliteration, following ISO 843. «Μεταγραφή» is
//      commoner in speech but also means transcription, which this Handbook uses
//      for a different act.
//   5. «απόσυρση» for withdrawing a copy. «Διαγραφή από το απόθεμα» is more
//      explicit and much longer.
//
// Quoted examples are left exactly as they appear in the catalogue, including the
// upper case and the «<<>>» the import made of Greek quotation marks.
